import assert from 'node:assert/strict'
import { parseInline, parseMarkdown } from '../src/lib/md.ts'

assert.equal(parseInline('σ~param~')[1].t, 'sub')
assert.equal(parseInline('σ~param~')[1].c[0].v, 'param')
assert.equal(parseInline('x^2^')[1].t, 'sup')
assert.deepEqual(parseInline('x~i~^2^').map(n => n.t), ['text', 'sub', 'sup'])
assert.equal(parseInline('σ~τ~')[1].c[0].v, 'τ')
assert.equal(parseInline('~~removed~~')[0].t, 'del')
assert.ok(parseInline('~~H~2~O~~')[0].c.some(n => n.t === 'sub'))
assert.equal(parseInline('H<sub>2</sub>O')[1].t, 'sub')
assert.equal(parseInline('x<sup>2</sup>')[1].t, 'sup')
assert.equal(parseInline('`σ~w~ x^2^`')[0].t, 'code')
assert.equal(parseMarkdown('~~~\nσ~w~ x^2^\n~~~')[0].t, 'code')
assert.ok(parseInline('σ\\~w\\~ x\\^2\\^').every(n => n.t === 'text'))
assert.ok(parseInline('σ~w x^2').every(n => n.t === 'text'))
assert.ok(parseInline('~~ ^^').every(n => n.t === 'text'))
assert.ok(parseInline('x~a b~').every(n => n.t === 'text'))
assert.equal(parseInline('x~a\\ b~')[1].c[0].v, 'a b')
assert.ok(!parseInline('σ_w file_name').some(n => n.t === 'sub'))
assert.equal(parseInline('https://example.com/~user~')[0].t, 'link')
assert.equal(parseInline('[[x~i~]]')[0].target, 'x~i~')
assert.ok(parseInline('**σ~w~**')[0].c.some(n => n.t === 'sub'))
assert.equal(parseMarkdown('| Metric |\n| --- |\n| σ~w~ x^2^ |')[0].rows[0][0].filter(n => n.t === 'sub' || n.t === 'sup').length, 2)
console.log('PASS: script syntax and regression assertions')
